def read_sheet(path, sheet):
    wb = openpyxl.load_workbook(path, data_only=False)
    ws = wb[sheet]
    rows = []
    for r in ws.iter_rows(values_only=True):
        if all(v is None or str(v).strip() == "" for v in r):
            continue
        rows.append(list(r))
    wb.close()
    return rows


def append_rows(ws, rows, start_col=1, header_style=None, keep_rows=1):
    """افزودن ردیف‌ها از ردیف بعد از آخرین ردیف دارای محتوا.

    keep_rows: تعداد ردیف‌های ابتدایی که نباید پاک شوند (پیش‌فرض: فقط سرستون).
    برای اجرای دوباره‌پذیر (idempotent)، ابتدا ردیف‌های داده قبلی حذف می‌شوند.
    """
    if ws.max_row > keep_rows:
        ws.delete_rows(keep_rows + 1, ws.max_row - keep_rows)
    first_empty = ws.max_row + 1
    for i, row in enumerate(rows):
        r = first_empty + i
        for j, val in enumerate(row):
            cell = ws.cell(row=r, column=start_col + j, value=val)
            if header_style and i == 0:
                cell.font = header_style


def add_validation_columns(ws, n_data_cols):
    """افزودن چهار ستون اعتبارسنجی به شیت‌هایی که ندارند."""
    start = n_data_cols + 1
    header = Font(bold=True, color="FFFFFF")
    fill = PatternFill("solid", fgColor="4472C4")
    for j, name in enumerate(VALIDATION_COLS):
        cell = ws.cell(row=1, column=start + j, value=name)
        cell.font = header
        cell.fill = fill
    return start


